historical_source AS (
    SELECT
        name AS package_name,
        LOWER(
            REGEXP_REPLACE(name, r'[-_.]+', '-')
        ) AS normalized_name,
        version,
        MIN(upload_time) AS first_upload_time,
        COUNT(*) AS distribution_file_count,
        ARRAY_AGG(
            DISTINCT summary IGNORE NULLS LIMIT 1
        )[SAFE_OFFSET(0)] AS summary,
        ARRAY_AGG(
            DISTINCT requires_python IGNORE NULLS LIMIT 1
        )[SAFE_OFFSET(0)] AS requires_python
    FROM `bigquery-public-data.pypi.distribution_metadata`
    WHERE LOWER(
        REGEXP_REPLACE(name, r'[-_.]+', '-')
    ) IN (
        SELECT package_name FROM target_packages
    )
    GROUP BY
        package_name,
        normalized_name,
        version
)

SELECT
    package_name,
    normalized_name,
    version,
    first_upload_time,
    distribution_file_count,
    summary,
    requires_python
FROM historical_source
ORDER BY
    normalized_name,
    first_upload_time,
    version;
