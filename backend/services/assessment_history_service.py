
"""
Persistent assessment history for TyposquatShield.

SQLite is used for local development and tests.
PostgreSQL is used when DATABASE_URL is configured.

Assessment records are append-only.
Database errors must not change assessment results.
"""

import json
import logging
import os
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

logger = logging.getLogger(__name__)

BASE = Path(__file__).resolve().parents[2]

DEFAULT_DATABASE_PATH = (
    BASE / "data" / "runtime" / "typosquatshield.db"
)

COLUMNS = (
    "id, created_at, package_name, package_version, "
    "assessment_context, assessment_status, risk_level, "
    "static_scan_status"
)


def get_database_path():
    configured = os.getenv("TPS_DATABASE_PATH")

    if configured:
        return Path(configured).expanduser()

    return DEFAULT_DATABASE_PATH


def get_database_url():
    return os.getenv("DATABASE_URL", "").strip()


def get_database_backend():
    # Explicit SQLite paths take precedence, including in tests.
    if os.getenv("TPS_DATABASE_PATH"):
        return "sqlite"

    url = get_database_url()

    if url.startswith(("postgresql://", "postgres://")):
        return "postgresql"

    if url:
        raise ValueError("Unsupported DATABASE_URL scheme.")

    return "sqlite"


def get_connection():
    """Retained for existing SQLite callers and tests."""
    if get_database_backend() != "sqlite":
        raise RuntimeError(
            "get_connection() is only available for SQLite."
        )

    path = get_database_path()
    path.parent.mkdir(parents=True, exist_ok=True)

    connection = sqlite3.connect(str(path), timeout=10)
    connection.row_factory = sqlite3.Row
    return connection


def get_postgres_connection():
    import psycopg
    from psycopg.rows import dict_row

    url = get_database_url()

    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://"):]

    return psycopg.connect(
        url,
        row_factory=dict_row,
        connect_timeout=10,
    )


def initialize_database():
    if get_database_backend() == "postgresql":
        with get_postgres_connection() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS assessment_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    created_at TEXT NOT NULL,
                    package_name TEXT NOT NULL,
                    package_version TEXT,
                    assessment_context TEXT NOT NULL,
                    assessment_status TEXT NOT NULL,
                    risk_level TEXT NOT NULL,
                    static_scan_status TEXT,
                    result_json TEXT NOT NULL
                )
                """
            )

            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_history_created_at
                ON assessment_history (created_at DESC)
                """
            )

            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_history_package_name
                ON assessment_history (package_name)
                """
            )

        return

    with get_connection() as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS assessment_history (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                created_at TEXT NOT NULL,
                package_name TEXT NOT NULL,
                package_version TEXT,
                assessment_context TEXT NOT NULL,
                assessment_status TEXT NOT NULL,
                risk_level TEXT NOT NULL,
                static_scan_status TEXT,
                result_json TEXT NOT NULL
            )
            """
        )

        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_history_created_at
            ON assessment_history (created_at DESC)
            """
        )

        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_history_package_name
            ON assessment_history (package_name)
            """
        )


def save_assessment(result):
    """Persist one completed assessment and return its ID."""
    initialize_database()

    timestamp = datetime.now(timezone.utc).isoformat()
    static_analysis = result.get("static_analysis") or {}

    values = (
        timestamp,
        result["package"],
        result.get("version"),
        result.get("assessment_context", "pypi"),
        result.get("assessment_status", "unknown"),
        result.get("risk_level", "Not Applicable"),
        static_analysis.get("scan_status"),
        json.dumps(result, ensure_ascii=False),
    )

    columns = """
        created_at,
        package_name,
        package_version,
        assessment_context,
        assessment_status,
        risk_level,
        static_scan_status,
        result_json
    """

    if get_database_backend() == "postgresql":
        with get_postgres_connection() as connection:
            row = connection.execute(
                f"""
                INSERT INTO assessment_history ({columns})
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING id
                """,
                values,
            ).fetchone()

            return row["id"]

    with get_connection() as connection:
        cursor = connection.execute(
            f"""
            INSERT INTO assessment_history ({columns})
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            values,
        )

        return cursor.lastrowid


def list_assessments(limit=50, offset=0):
    """Return newest assessments without full result JSON."""
    initialize_database()

    limit = max(1, min(int(limit), 200))
    offset = max(0, int(offset))

    if get_database_backend() == "postgresql":
        with get_postgres_connection() as connection:
            rows = connection.execute(
                f"""
                SELECT {COLUMNS}
                FROM assessment_history
                ORDER BY id DESC
                LIMIT %s OFFSET %s
                """,
                (limit, offset),
            ).fetchall()

        return [dict(row) for row in rows]

    with get_connection() as connection:
        rows = connection.execute(
            f"""
            SELECT {COLUMNS}
            FROM assessment_history
            ORDER BY id DESC
            LIMIT ? OFFSET ?
            """,
            (limit, offset),
        ).fetchall()

    return [dict(row) for row in rows]


def get_assessment(assessment_id):
    """Retrieve a complete stored assessment by ID."""
    initialize_database()

    if get_database_backend() == "postgresql":
        with get_postgres_connection() as connection:
            row = connection.execute(
                """
                SELECT *
                FROM assessment_history
                WHERE id = %s
                """,
                (assessment_id,),
            ).fetchone()

    else:
        with get_connection() as connection:
            row = connection.execute(
                """
                SELECT *
                FROM assessment_history
                WHERE id = ?
                """,
                (assessment_id,),
            ).fetchone()

    if row is None:
        return None

    record = dict(row)
    record["result"] = json.loads(record.pop("result_json"))

    return record
